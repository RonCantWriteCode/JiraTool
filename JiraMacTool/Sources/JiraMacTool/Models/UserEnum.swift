    static func getEmail(for name: String) -> String? {
        // First check built-in enum
        if let builtIn = UserEnum.allCases.first(where: { $0.rawValue == name }) {
            return builtIn.email
        }
        // Then check dynamically added mappings from UserDefaults
        let dynamicMap = UserEnum.loadDynamicMappings()
        return dynamicMap[name]
    }

    // MARK: - Dynamic User Mappings (User-Added via Confirm Dialog)

    private static let dynamicMappingsKey = "user_email_dynamic_mappings"

    /// Load all dynamically added user->email mappings from UserDefaults
    static func loadDynamicMappings() -> [String: String] {
        guard let data = UserDefaults.standard.data(forKey: dynamicMappingsKey),
              let dict = try? JSONDecoder().decode([String: String].self, from: data) else {
            return [:]
        }
        return dict
    }

    /// Save dynamically added user->email mappings to UserDefaults
    static func saveDynamicMappings(_ mappings: [String: String]) {
        if let data = try? JSONEncoder().encode(mappings) {
            UserDefaults.standard.set(data, forKey: dynamicMappingsKey)
        }
    }

    /// Add new user->email mappings (merge with existing)
    static func addDynamicMappings(_ newMappings: [String: String]) {
        var existing = loadDynamicMappings()
        for (name, email) in newMappings {
            existing[name] = email
        }
        saveDynamicMappings(existing)
    }

    /// Get all unknown users that have no email mapping
    static func getUnknownUsers(from names: [String]) -> [String] {
        return names.filter { getEmail(for: $0) == nil }
    }

    /// Get all user mappings (built-in + dynamic) as a dictionary
    static func getAllMappings() -> [(name: String, email: String, isBuiltIn: Bool)] {
        var result: [(name: String, email: String, isBuiltIn: Bool)] = []

        // Add built-in enum mappings
        for userCase in UserEnum.allCases {
            result.append((name: userCase.rawValue, email: userCase.email, isBuiltIn: true))
        }

        // Add dynamic mappings
        let dynamicMap = loadDynamicMappings()
        for (name, email) in dynamicMap {
            // Skip if already exists in built-in (shouldn't happen, but just in case)
            if !result.contains(where: { $0.name == name }) {
                result.append((name: name, email: email, isBuiltIn: false))
            }
        }

        return result.sorted { $0.name < $1.name }
    }

    /// Update email for a specific user (dynamic mappings only)
    static func updateEmail(for name: String, email: String) {
        var dynamicMap = loadDynamicMappings()
        dynamicMap[name] = email
        saveDynamicMappings(dynamicMap)
    }
